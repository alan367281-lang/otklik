//! Буфер обмена на macOS (NSPasteboard): сохранить всё, что там лежит,
//! положить свой текст, вернуть как было. Те же функции, что на Windows.

#![allow(unused_unsafe)]

use objc2::rc::Retained;
use objc2::runtime::ProtocolObject;
use objc2_app_kit::{NSPasteboard, NSPasteboardItem, NSPasteboardTypeString, NSPasteboardWriting};
use objc2_foundation::{NSArray, NSData, NSString};

/// Владельца у буфера на Mac нет — тип ради одинаковых функций с Windows.
pub type Owner = ();

pub fn owner_window() -> Owner {}

pub fn no_owner() -> Owner {}

/// Пометки для менеджеров буфера (соглашение nspasteboard.org): «временное,
/// не запоминать» — наша подмена не должна засорять историю.
const PRIVATE_TYPES: [&str; 2] = [
    "org.nspasteboard.TransientType",
    "org.nspasteboard.AutoGeneratedType",
];

/// Содержимое буфера: элементы, у каждого — пары «тип — байты».
#[derive(Default)]
pub struct Saved(Vec<Vec<(String, Vec<u8>)>>);

fn board() -> Retained<NSPasteboard> {
    unsafe { NSPasteboard::generalPasteboard() }
}

pub fn save(_: Owner) -> Result<Saved, String> {
    let pb = board();
    let mut out = Vec::new();
    unsafe {
        if let Some(items) = pb.pasteboardItems() {
            for item in items.to_vec() {
                let mut pairs = Vec::new();
                for t in item.types().to_vec() {
                    if let Some(data) = item.dataForType(&t) {
                        pairs.push((t.to_string(), data.to_vec()));
                    }
                }
                out.push(pairs);
            }
        }
    }
    Ok(Saved(out))
}

fn mark_private(pb: &NSPasteboard) {
    let empty = NSData::new();
    for t in PRIVATE_TYPES {
        unsafe {
            pb.setData_forType(Some(&empty), &NSString::from_str(t));
        }
    }
}

/// Положить текст. Возвращает номер версии буфера — по нему потом видно,
/// не скопировал ли человек что-то своё, пока мы ждали.
pub fn set_text(_: Owner, text: &str) -> Result<u32, String> {
    let pb = board();
    unsafe {
        pb.clearContents();
        if !pb.setString_forType(&NSString::from_str(text), NSPasteboardTypeString) {
            return Err("macOS не приняла текст в буфер обмена".into());
        }
    }
    mark_private(&pb);
    Ok(sequence())
}

pub fn restore(_: Owner, saved: &Saved) -> Result<(), String> {
    let pb = board();
    unsafe {
        pb.clearContents();
        if saved.0.is_empty() {
            return Ok(());
        }
        let items: Vec<Retained<ProtocolObject<dyn NSPasteboardWriting>>> = saved
            .0
            .iter()
            .map(|pairs| {
                let item = NSPasteboardItem::new();
                for (t, bytes) in pairs {
                    item.setData_forType(&NSData::with_bytes(bytes), &NSString::from_str(t));
                }
                ProtocolObject::from_retained(item)
            })
            .collect();
        pb.writeObjects(&NSArray::from_retained_slice(&items));
    }
    Ok(())
}

pub fn sequence() -> u32 {
    unsafe { board().changeCount() as u32 }
}

/// Текст из буфера — для подстановки {clipboard}. Нет текста — пусто.
pub fn get_text(_: Owner) -> String {
    unsafe {
        board()
            .stringForType(NSPasteboardTypeString)
            .map(|s| s.to_string())
            .unwrap_or_default()
    }
}
