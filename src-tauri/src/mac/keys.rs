/// Код клавиши Mac → код Windows. None — клавиша, которой нет в правилах.
pub fn to_vk(keycode: u16) -> Option<u16> {
    TABLE.iter().find(|(k, _)| *k == keycode).map(|(_, vk)| *vk)
}

/// Код Windows → код клавиши Mac (первый подходящий).
pub fn from_vk(vk: u16) -> Option<u16> {
    TABLE.iter().find(|(_, v)| *v == vk).map(|(k, _)| *k)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn roundtrip_and_known_keys() {
        assert_eq!(to_vk(0x00), Some(0x41)); // A
        assert_eq!(to_vk(0x12), Some(0x31)); // 1
        assert_eq!(to_vk(0x31), Some(0x20)); // пробел
        assert_eq!(from_vk(0x56), Some(0x09)); // V — для Cmd+V
        for (k, vk) in TABLE {
            assert_eq!(to_vk(*k), Some(*vk));
        }
        // Enter есть дважды (основной и на цифровом блоке) — назад основной.
        assert_eq!(from_vk(0x0D), Some(0x24));
    }
}
